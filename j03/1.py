# data type

# int

a = 10
print(a)
print(type(a))

# float

b = -7.8
b2 = 10.0

print(b)
print(type(b))

print(b2,  '\n', type(b2))

# str

c = 'salam'
print(c, "\n", type(c))

d = ""
print(d, type(d))

# bool

e = True
print(e, "\n", type(e))

f = False
print(f, "\n", type(f))

g = not e
print(g, "\n", type(g))

h = not f
print(h, "\n", type(h))
